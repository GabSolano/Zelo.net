CREATE TABLE dbo.USUARIO (
    id NVARCHAR(36) NOT NULL PRIMARY KEY,
    nome NVARCHAR(150) NOT NULL,
    email NVARCHAR(180) NOT NULL UNIQUE,
    telefone NVARCHAR(40) NOT NULL,
    papel NVARCHAR(30) NOT NULL CHECK (papel IN ('IDOSO', 'FAMILIAR', 'GUARDIAO', 'ADMIN', 'SERVICO')),
    senha_hash NVARCHAR(256) NOT NULL
);

CREATE TABLE dbo.USUARIO_DISPOSITIVO (
    id NVARCHAR(36) NOT NULL PRIMARY KEY,
    usuario_id NVARCHAR(36) NOT NULL REFERENCES dbo.USUARIO(id) ON DELETE CASCADE,
    push_token NVARCHAR(256) NOT NULL
);

CREATE TABLE dbo.IDOSO (
    id NVARCHAR(36) NOT NULL PRIMARY KEY,
    usuario_id NVARCHAR(36) NOT NULL REFERENCES dbo.USUARIO(id),
    nome NVARCHAR(150) NOT NULL,
    data_nascimento NVARCHAR(10) NOT NULL,
    observacoes NVARCHAR(500) NULL
);

CREATE TABLE dbo.CONSENTIMENTO (
    id NVARCHAR(36) NOT NULL PRIMARY KEY,
    idoso_id NVARCHAR(36) NOT NULL REFERENCES dbo.IDOSO(id) ON DELETE CASCADE,
    versao_termo NVARCHAR(30) NOT NULL,
    aceito_em DATETIME2 NOT NULL,
    revogado_em DATETIME2 NULL
);

CREATE TABLE dbo.CASA (
    id NVARCHAR(36) NOT NULL PRIMARY KEY,
    idoso_id NVARCHAR(36) NOT NULL REFERENCES dbo.IDOSO(id) ON DELETE CASCADE,
    endereco NVARCHAR(250) NOT NULL,
    bairro NVARCHAR(100) NOT NULL,
    cidade NVARCHAR(100) NOT NULL
);

CREATE TABLE dbo.SENSOR (
    id NVARCHAR(36) NOT NULL PRIMARY KEY,
    casa_id NVARCHAR(36) NOT NULL REFERENCES dbo.CASA(id) ON DELETE CASCADE,
    comodo NVARCHAR(30) NOT NULL CHECK (comodo IN ('QUARTO', 'BANHEIRO', 'COZINHA', 'GELADEIRA', 'ENTRADA')),
    tipo_sensor NVARCHAR(30) NOT NULL CHECK (tipo_sensor IN ('PRESENCA', 'PORTA')),
    ativo BIT NOT NULL DEFAULT 1,
    CONSTRAINT UQ_SENSOR_CASA_COMODO UNIQUE (casa_id, comodo)
);

CREATE TABLE dbo.CONTATO_APOIO (
    id NVARCHAR(36) NOT NULL PRIMARY KEY,
    idoso_id NVARCHAR(36) NOT NULL REFERENCES dbo.IDOSO(id) ON DELETE CASCADE,
    usuario_id NVARCHAR(36) NOT NULL REFERENCES dbo.USUARIO(id),
    papel NVARCHAR(30) NOT NULL CHECK (papel IN ('FAMILIAR', 'GUARDIAO')),
    ordem INT NOT NULL CHECK (ordem >= 1),
    CONSTRAINT UQ_CONTATO_IDOSO_ORDEM UNIQUE (idoso_id, ordem)
);

CREATE TABLE dbo.LEMBRETE (
    id NVARCHAR(36) NOT NULL PRIMARY KEY,
    idoso_id NVARCHAR(36) NOT NULL REFERENCES dbo.IDOSO(id) ON DELETE CASCADE,
    texto NVARCHAR(250) NOT NULL,
    horario NVARCHAR(5) NOT NULL,
    dias_semana NVARCHAR(60) NOT NULL,
    ativo BIT NOT NULL DEFAULT 1,
    criado_por NVARCHAR(36) NOT NULL
);

CREATE TABLE dbo.LEMBRETE_REGISTRO (
    id NVARCHAR(36) NOT NULL PRIMARY KEY,
    lembrete_id NVARCHAR(36) NOT NULL REFERENCES dbo.LEMBRETE(id) ON DELETE CASCADE,
    previsto_para DATETIME2 NOT NULL,
    status NVARCHAR(30) NOT NULL CHECK (status IN ('PENDENTE', 'CONFIRMADO', 'NAO_CONFIRMADO')),
    confirmado_em DATETIME2 NULL,
    CONSTRAINT UQ_REGISTRO_LEMBRETE_PREVISTO UNIQUE (lembrete_id, previsto_para)
);

CREATE TABLE dbo.IDEMPOTENCY_RECORD (
    chave NVARCHAR(120) NOT NULL PRIMARY KEY,
    request_hash NVARCHAR(128) NOT NULL,
    status_code INT NOT NULL,
    response_body NVARCHAR(MAX) NOT NULL,
    criado_em DATETIME2 NOT NULL
);

